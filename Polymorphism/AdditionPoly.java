class AdditionPoly{
	public static String add(int a,int b){
		int sum=a+b;
		return "Sum is: "+sum;
	}
	public static String add(int a,int b,int c){
		int sum=a+b+c;
		return "Sum is: "+sum;
	}
	public static String add(double a,double b){
		double sum=a+b;
		return "Sum is: "+sum;
	}
	public static String add(double a,double b,double c){
		double sum=a+b+c;
		return "Sum is: "+sum;
	}
}